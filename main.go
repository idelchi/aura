/*
Aura is an agentic coding CLI assistant.

Usage:

	aura [command] [flags]

Use "aura --help" for more information.
*/
package main

import (
	"context"
	"errors"
	"fmt"
	"os"

	"github.com/idelchi/aura/internal/cli"
	"github.com/idelchi/aura/internal/cli/core"
	"github.com/idelchi/aura/pkg/sandbox"
)

// version is the application version injected at build time.
var version = "unknown - unofficial & generated by unknown"

// main is the entry point of the application.
func main() {
	// The confining launcher for sandboxed MCP servers must not parse flags or load env files.
	if len(os.Args) > 1 && os.Args[1] == sandbox.ExecArg {
		sandbox.ExecMain(os.Args[2:])
	}

	cli.SetEmbeddedConfig(embeddedConfig)

	if err := cli.Execute(version); err != nil {
		if !errors.Is(err, context.Canceled) && !errors.Is(err, core.ErrReported) {
			fmt.Fprintln(os.Stderr, err)
		}

		os.Exit(1)
	}

	os.Exit(0)
}
